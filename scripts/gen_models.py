#!/usr/bin/env python3
"""Regenerate ``copilot/models/generated`` from the JSON Schemas.

Purpose: keep the Pydantic models a pure projection of the schemas.
Use case: run locally and in CI; CI fails if the committed models differ.
Example: ``python scripts/gen_models.py``

The generator is pinned to datamodel-code-generator 0.96.0. Do not
hand-edit files under ``copilot/models/generated``.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

GENERATOR_VERSION = "0.96.0"
QUAL_SCHEMA_ID = "https://capstone.local/lbs-copilot/schemas/qualification_details/v1.0.0"

REPO = Path(__file__).resolve().parents[1]
CONTRACTS = REPO / "contracts" / "interpretation"
QUAL_SCHEMA = REPO / "schemas" / "qualification_details.schema.json"
OUTPUT = REPO / "copilot" / "models" / "generated"

# Staged filenames become the generated module names.
_STAGED = {
    "turn.schema.json": "turn.json",
    "known_fact.schema.json": "known_fact.json",
    "interpretation_input.schema.json": "interpretation_input.json",
    "interpretation_output.schema.json": "interpretation_output.json",
}

_FLAGS = [
    "--input-file-type",
    "jsonschema",
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--target-python-version",
    "3.12",
    "--enum-field-as-literal",
    "all",
    "--use-union-operator",
    "--no-use-annotated",
    "--use-standard-collections",
    "--field-constraints",
    "--extra-fields",
    "forbid",
    "--disable-timestamp",
    "--use-default",
    "--strict-nullable",
    "--formatters",
    "builtin",
    "--reuse-model",
    "--enable-version-header",
    "--keep-model-order",
]


def _require_generator() -> None:
    try:
        installed = version("datamodel-code-generator")
    except PackageNotFoundError:
        print(
            "datamodel-code-generator is not installed. "
            f"Install datamodel-code-generator=={GENERATOR_VERSION}.",
            file=sys.stderr,
        )
        raise SystemExit(2) from None
    if installed != GENERATOR_VERSION:
        print(
            f"datamodel-code-generator {installed} is installed; "
            f"{GENERATOR_VERSION} is required.",
            file=sys.stderr,
        )
        raise SystemExit(2)


def _stage(directory: Path) -> None:
    """Copy schemas into one directory the generator can resolve.

    ``qualification_details.schema.json`` stays the source of truth. The
    interpretation output schema points at its ``$id``. The generator
    resolves file-relative ``$ref``s, so the staged copy rewrites that
    ``$id`` to the staged file name. Validators keep using the ``$id``.
    """
    (directory / "qualification_details.json").write_bytes(QUAL_SCHEMA.read_bytes())
    for src_name, dst_name in _STAGED.items():
        text = (CONTRACTS / src_name).read_text(encoding="utf-8")
        text = text.replace('"turn.schema.json"', '"turn.json"')
        text = text.replace('"known_fact.schema.json"', '"known_fact.json"')
        text = text.replace(f'"{QUAL_SCHEMA_ID}"', '"qualification_details.json"')
        (directory / dst_name).write_text(text, encoding="utf-8")


def _write_package_init() -> None:
    header = (
        "# Generated by scripts/gen_models.py. Do not hand-edit.\n"
        "# datamodel-code-generator "
        f"{GENERATOR_VERSION} writes the sibling modules.\n"
        "# copilot.models re-exports the public classes.\n"
    )
    (OUTPUT / "__init__.py").write_text(header, encoding="utf-8")


def main() -> int:
    _require_generator()
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir(parents=True)
    with tempfile.TemporaryDirectory(prefix="interpretation-models-") as tmp:
        stage = Path(tmp)
        _stage(stage)
        command = [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(stage),
            "--output",
            str(OUTPUT),
            *_FLAGS,
        ]
        completed = subprocess.run(command, check=False)
        if completed.returncode != 0:
            return completed.returncode
    _write_package_init()
    print(f"Wrote {OUTPUT} with datamodel-code-generator {GENERATOR_VERSION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
